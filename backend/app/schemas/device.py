"""Device and provisioning request/response models (PRD 2, sections 32-37)."""

import uuid
from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, field_validator

from app.models.device import HARDWARE_ID_PATTERN
from app.models.enums import DEVICE_CONNECTION_STATUSES, DEVICE_PROVISIONING_STATUSES

ConnectionStatus = Literal["unknown", "online", "offline"]
ProvisioningStatus = Literal["unclaimed", "claimed"]
SessionState = Literal["pending", "claimed", "expired"]

assert set(DEVICE_CONNECTION_STATUSES) == set(ConnectionStatus.__args__)  # type: ignore[attr-defined]
assert set(DEVICE_PROVISIONING_STATUSES) == set(ProvisioningStatus.__args__)  # type: ignore[attr-defined]

HardwareId = Annotated[str, StringConstraints(pattern=HARDWARE_ID_PATTERN)]

#: Room for a prefix and 43 characters of base64url, with slack.
Token = Annotated[str, StringConstraints(min_length=16, max_length=128)]

#: 32 bytes, hex encoded, as generated by the firmware.
BootstrapSecret = Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]

FirmwareVersion = Annotated[str, StringConstraints(min_length=1, max_length=32)]

#: A user-facing label (PRD 2, section 37). Never identity.
DISPLAY_NAME_MAX_LENGTH = 40


# --- app-facing -------------------------------------------------------------


class ProvisioningSessionCreate(BaseModel):
    #: Read by the app from the robot over BLE, after verification.
    hardware_id: HardwareId
    #: The person this Nura is for. Defaults to the account's own profile, or
    #: the person being helped in assisted setup.
    profile_id: uuid.UUID | None = None


class ProvisioningSessionCreated(BaseModel):
    id: uuid.UUID
    hardware_id: str
    #: Shown once. The app passes it to the robot and then forgets it.
    provisioning_token: str
    expires_at: datetime
    #: Where the robot should reach this API once it is on Wi-Fi.
    device_api_base_url: str


class ProvisioningSessionRead(BaseModel):
    id: uuid.UUID
    hardware_id: str
    state: SessionState
    expires_at: datetime
    #: Set once the robot has claimed.
    device_id: uuid.UUID | None


class DeviceRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    hardware_id: str
    display_name: str
    device_type: str
    firmware_version: str | None
    provisioning_status: ProvisioningStatus
    connection_status: ConnectionStatus
    last_seen_at: datetime | None
    claimed_at: datetime | None
    setup_completed_at: datetime | None
    introduced_at: datetime | None
    owner_profile_id: uuid.UUID | None
    created_at: datetime
    updated_at: datetime


class DeviceUpdate(BaseModel):
    display_name: str = Field(min_length=1, max_length=DISPLAY_NAME_MAX_LENGTH)

    @field_validator("display_name", mode="before")
    @classmethod
    def _tidy(cls, value: object) -> object:
        """Trims whitespace and refuses a name that is blank or has control characters."""
        if not isinstance(value, str):
            return value
        cleaned = " ".join(value.split())
        if any(ord(character) < 32 for character in value if character not in " \t"):
            raise ValueError("Use letters, numbers and spaces only.")
        return cleaned


class DeviceStatusRead(BaseModel):
    device_id: uuid.UUID
    connection_status: ConnectionStatus
    last_seen_at: datetime | None
    #: True once a heartbeat has arrived using the token from the latest claim.
    checked_in_since_claim: bool
    online_threshold_seconds: int
    provisioning_status: ProvisioningStatus
    firmware_version: str | None
    setup_completed: bool
    introduction_pending: bool


# --- robot-facing -----------------------------------------------------------


class DeviceClaim(BaseModel):
    hardware_id: HardwareId
    provisioning_token: Token
    bootstrap_secret: BootstrapSecret
    firmware_version: FirmwareVersion | None = None


class DeviceClaimed(BaseModel):
    device_id: uuid.UUID
    #: The robot's credential from now on. Shown once.
    device_token: str
    heartbeat_interval_seconds: int


class HeartbeatCreate(BaseModel):
    firmware_version: FirmwareVersion | None = None
    #: The robot has just played the introduction the backend asked for.
    introduction_played: bool = False


class HeartbeatRead(BaseModel):
    heartbeat_interval_seconds: int
    #: Play the first introduction now (PRD 2, section 38).
    introduce: bool
    server_time: datetime
